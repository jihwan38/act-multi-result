#!/usr/bin/env python3
"""Build one case, compile its HLO, and compare the final assembly with that HLO."""
import argparse
import json
from pathlib import Path
import re
import shutil
import sys

from .common import (ROOT, TOOLCHAINS, case_config, command, digest, main_guard,
                     process_env, toolchain_lock, write_json)
from prepare_sources import prepare


def built_target(config, toolchain):
    base = ROOT / "build" / toolchain
    target = base / "targets" / config["target"]
    binary = base / "backends" / config["target"]
    if not binary.is_file() or not list((target / "oracle/build").glob("print_handler_ext*.so")):
        raise ValueError("Generate the compiler and Oracle by running the ISA Python file first")
    return target, binary


def build_case(name, toolchain=None, force=False):
    directory, config, toolchain = case_config(name, toolchain)
    provenance = prepare(toolchain, force)
    env = process_env(toolchain)
    log = ROOT / "build" / toolchain / "logs" / f"{config['target']}-build.log"
    print(f"Running python {directory / config['isa']}; log: {log}", flush=True)
    command([sys.executable, directory / config["isa"]], env=env, log=log)
    target, binary = built_target(config, toolchain)
    print(f"Compiler: {binary}\nGenerated code: {target}", flush=True)
    return target, binary, provenance


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("case")
    parser.add_argument("--toolchain", choices=TOOLCHAINS)
    parser.add_argument("--workload", type=Path, help="HLO path; defaults to the case's example workload")
    parser.add_argument("--skip-build", action="store_true", help="Use the compiler and Oracle already generated by the ISA script")
    parser.add_argument("--force", action="store_true", help="Also replace edited prepared sources")
    args = parser.parse_args()
    if args.skip_build and args.force:
        parser.error("--skip-build and --force cannot be combined")
    directory, config, selected = case_config(args.case, args.toolchain)
    hlo = (args.workload or directory / config["default_workload"]).resolve()
    if not hlo.is_file() or hlo.suffix != ".hlo":
        raise ValueError(f"Expected an existing .hlo file: {hlo}")
    if not re.fullmatch(r"[A-Za-z0-9_-]+", hlo.stem):
        raise ValueError("Workload filename must use letters, digits, underscores or hyphens")
    with toolchain_lock(selected):
        if args.skip_build:
            target, binary = built_target(config, selected)
            build = json.loads((ROOT / "build" / selected / "src/provenance.json").read_text())
        else:
            target, binary, build = build_case(args.case, selected, args.force)
        env = process_env(selected)
        output = ROOT / "build" / selected / "runs" / args.case / hlo.stem
        output.mkdir(parents=True, exist_ok=True)
        # Replace only this shortcut's outputs, including after a manual run.
        # The compiler itself recreates its --log directory.
        for name in ("assembly.py", "assembly.py.allocation.json", "selected.pii", "verification.json", "verify.log"):
            (output / name).unlink(missing_ok=True)
        record = {"case": args.case, "toolchain": selected, "hlo": str(hlo),
                  "hlo_sha256": digest(hlo), "source_fingerprint": build["fingerprint"],
                  "isa_sha256": digest(directory / config["isa"]), "skip_build": args.skip_build,
                  "binary_sha256": digest(binary), "status": "running"}
        write_json(output / "run.json", record)
        assembly = output / "assembly.py"
        print(f"Compiling {hlo.name}; results: {output}", flush=True)
        try:
            command([binary, "--input", hlo, "--output", assembly, "--log", output / "compiler"],
                    env=env, log=output / "compile.log")
            if not assembly.is_file() or not assembly.stat().st_size:
                raise RuntimeError("Compiler exited without producing an assembly; see compile.log")
            match = re.search(r"^# PII number: (\d+)$", assembly.read_text(), re.M)
            if not match:
                raise RuntimeError("Assembly does not identify its selected PII")
            pii = output / "compiler" / f"{match[1]}.pii"
            shutil.copy2(pii, output / "selected.pii")
            command([sys.executable, ROOT / "scripts/verify.py",
                     "--hlo", hlo, "--assembly", assembly,
                     "--report", output / "verification.json"],
                    env=env, log=output / "verify.log")
            verification = json.loads((output / "verification.json").read_text())
            record.update(status="passed", selected_pii=int(match[1]), assembly_sha256=digest(assembly),
                          verification=verification)
        except Exception as error:
            record.update(status="failed", error=str(error))
            raise
        finally:
            write_json(output / "run.json", record)
        print(f"PASS: {args.case} / {selected}; {verification['datasets']} input sets matched exactly.")
        print(f"Assembly: {assembly}\nVerification: {output / 'verification.json'}")


if __name__ == "__main__":
    main_guard(main)
